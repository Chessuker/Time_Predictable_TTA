"""Generate baseline/sw/pid/pid_const.h from host/plant_model, so the C PID of
the soft-core baseline uses the same gains and limits as FixedPID and the TTA
program (one source of numbers, like plant_pkg.sv).

    py -m host.baseline.gen_c            write the header
    py -m host.baseline.gen_c --check    exit 1 if the committed file is stale
"""
import sys
from pathlib import Path

from host.plant_model import model as m

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "baseline" / "sw" / "pid" / "pid_const.h"


def generate():
    w = ["// GENERATED by `py -m host.baseline.gen_c` (host/baseline/gen_c.py). Do not edit.",
         "// FixedPID constants of host/plant_model/model.py.",
         "#ifndef PID_CONST_H",
         "#define PID_CONST_H",
         ""]
    for name, value, note in [
        ("PID_KPQ", m.KPQ, "Kp in Q.SH"),
        ("PID_KDQ", m.KDQ, "Kd in Q.SH (per period, on the measurement)"),
        ("PID_KIQ", m.KIQ, "Ki in Q.SH (per period)"),
        ("PID_SH", m.SH, "gain fraction bits"),
        ("PID_E_CLAMP", m.E_CLAMP, "error clamp before the multiplies"),
        ("PID_U_MAX", m.U_MAX, "pwm_cmd full scale"),
        ("PID_ACC_MAX", m.ACC_MAX, "integrator clamp, U_MAX << SH"),
    ]:
        w.append(f"#define {name:<12} {value:>10}   // {note}")
    w += ["", "#endif", ""]
    return "\n".join(w)


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    text = generate()
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else None
    if "--check" in argv:
        if current != text:
            print(f"{OUT} is stale; run py -m host.baseline.gen_c", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
